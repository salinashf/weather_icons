  static IconData fromString(
      String name, {
        IconData? fallback,
      }) {
    final target = name.replaceAll('_', '-');
    final icon = _all[target];

    if (icon != null) {
      return icon;
    } else if (fallback != null) {
      return fallback;
    } else {
      throw ArgumentError('Unsupported icon $name, with no fallback');
    }
  }

